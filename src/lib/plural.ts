/**
 * Українська форма слова після числа.
 *
 * Правило просте, але помиляються в ньому щоразу — і «1 задач поза періодом»
 * впадає в око сильніше, ніж здається. Одна реалізація на весь застосунок:
 * інтерфейс і так рахує задачі, дні й години в кількох різних місцях.
 */

/**
 * @param one   форма для 1, 21, 31… — «задача», «день»
 * @param few   форма для 2–4, 22–24… — «задачі», «дні»
 * @param many  форма для 5–20, 25–30… — «задач», «днів»
 */
export function pluralUk(n: number, one: string, few: string, many: string): string {
  const abs = Math.abs(Math.trunc(n));
  const mod10 = abs % 10;
  const mod100 = abs % 100;
  // 11–14 — виняток: попри останню цифру, вони беруть форму «багато»
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}

/** «1 задача» / «2 задачі» / «5 задач» */
export const tasksWord = (n: number) => pluralUk(n, 'задача', 'задачі', 'задач');

/** «1 день» / «2 дні» / «5 днів» */
export const daysWord = (n: number) => pluralUk(n, 'день', 'дні', 'днів');
